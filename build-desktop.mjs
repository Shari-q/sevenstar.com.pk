import { copyFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.dirname(fileURLToPath(import.meta.url));
const assetsDir = path.join(root, 'dist', 'assets');
const cssFile = (await readdir(assetsDir)).find((file) => /^index-.*\.css$/.test(file));

if (!cssFile) {
  throw new Error('Production CSS was not generated by Vite.');
}

await copyFile(path.join(assetsDir, cssFile), path.join(root, 'dist', 'desktop.css'));
await build({
  entryPoints: [path.join(root, 'src', 'main.jsx')],
  outfile: path.join(root, 'dist', 'desktop.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  define: {
    'import.meta.env.BASE_URL': '"/"',
  },
  loader: {
    '.css': 'empty',
    '.png': 'dataurl',
  },
});
